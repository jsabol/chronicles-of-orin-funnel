import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "dnd-5e-srd-markdown-master", "spells.md");
const outputPath = path.join(root, "src", "data", "cantrips.ts");
const markdown = await readFile(sourcePath, "utf8");
const sections = markdown.split(/^#### /m).slice(1);

const plainText = (value) =>
  value
    .replace(/^\*\*Components:\*\*.*$/gm, "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\*\*|_/g, "")
    .replace(/\s+/g, " ")
    .replace(/\bAdvantage\b/g, "Adv")
    .replace(/\bDisadvantage\b/g, "Disadv")
    .replace(/\badvantage\b/g, "adv")
    .replace(/\bdisadvantage\b/g, "disadv")
    .replace(/\bStrength\b/g, "STR")
    .replace(/\bDexterity\b/g, "DEX")
    .replace(/\bConstitution\b/g, "CON")
    .replace(/\bIntelligence\b/g, "INT")
    .replace(/\bWisdom\b/g, "WIS")
    .replace(/\bCharisma\b/g, "CHA")
    .trim();

const cantrips = sections.flatMap((section) => {
  const lines = section.split(/\r?\n/);
  const name = lines.shift()?.trim();
  const kind = lines.find((line) => /^_.*Cantrip \(.+\)_$/.test(line.trim()));
  if (!name || !kind) return [];

  const classes = kind
    .slice(kind.indexOf("(") + 1, kind.lastIndexOf(")"))
    .split(", ");
  const field = (label) =>
    lines
      .find((line) => line.startsWith(`**${label}:**`))
      ?.slice(label.length + 5)
      .trim() ?? "";
  const descriptionStart = lines.findIndex((line) =>
    line.startsWith("**Duration:**"),
  );
  const description = plainText(lines.slice(descriptionStart + 1).join("\n"));

  return [
    {
      name,
      classes,
      castingTime: field("Casting Time"),
      range: field("Range"),
      duration: field("Duration"),
      description,
    },
  ];
});

// Retained for the Wode Elf ancestry even though it isn't in SRD 5.2.
cantrips.push({
  name: "Thorn Whip",
  classes: ["Druid"],
  castingTime: "1 action",
  range: "30 feet",
  duration: "Instantaneous",
  description:
    "You create a long vine-like whip covered in thorns that lashes out at a creature within range. Make a melee spell attack. On a hit, the target takes 1d6 piercing damage and, if it is Large or smaller, you pull it up to 10 feet closer. Damage increases by 1d6 at 5th, 11th, and 17th level.",
});

const serialized = (value) => JSON.stringify(value, null, 2);
const descriptionOverrides = new Map([
  [
    "Elementalism",
    "Create 1 of the following. Beckon Air. A breeze ripples cloth, stirs dust, rustles leaves, and closes open doors and shutters in a 5-foot Cube unless they are held open. Beckon Earth. Coat surfaces in a 5-foot-square area with a thin layer of dust or sand, or make one word appear in your handwriting in dirt or sand. Beckon Fire. Fill a 5-foot Cube with harmless embers and colored, scented smoke. Choose the color and scent. The embers can light candles, torches, or lamps there. The smoke's scent lasts 1 minute. Beckon Water. Cool mist lightly dampens creatures and objects in a 5-foot Cube, or create 1 cup of clean water in an open container or on a surface; the water evaporates in 1 minute. Sculpt Element. Shape dirt, sand, fire, smoke, mist, or water that fits in a 1-foot Cube into a crude form, such as a creature, for 1 hour.",
  ],
]);
const wizardCantrips = cantrips
  .filter((spell) => spell.classes.includes("Wizard"))
  .map((spell) => spell.name);
const output = `// Generated from dnd-5e-srd-markdown-master/spells.md by
// npm run generate:srd. Do not edit this file by hand.
export interface SrdCantrip {
  name: string;
  castingTime: string;
  range: string;
  duration: string;
  description: string;
}

export const SRD_CANTRIPS: readonly SrdCantrip[] = ${serialized(
  cantrips.map(({ classes: _classes, ...spell }) => ({
    ...spell,
    description: descriptionOverrides.get(spell.name) ?? spell.description,
  })),
)};

export const CANTRIPS = SRD_CANTRIPS.map((spell) => spell.name);

export const SRD_CANTRIP_BY_NAME = new Map(
  SRD_CANTRIPS.map((spell) => [spell.name, spell]),
);

export const formatSrdCantrip = (name: string): string => {
  const spell = SRD_CANTRIP_BY_NAME.get(name);
  return spell
    ? \`${"${spell.name}"}. Casting Time: ${"${spell.castingTime}"}. Range: ${"${spell.range}"}. Duration: ${"${spell.duration}"}. ${"${spell.description}"}\`
    : name;
};

export const WIZARD_CANTRIPS = ${serialized(wizardCantrips)} as const;
`;

await writeFile(outputPath, output, "utf8");
console.log("Generated 27 SRD 5.2 cantrips plus Thorn Whip.");
